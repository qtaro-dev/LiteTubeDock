    public const string HelpText = """
LiteTube Dock について

LiteTube Dock は、YouTube や登録済みURLを専用の1ウィンドウで開く軽量Webプレイヤーです。
通常ブラウザの代替ではなく、作業BGM、YouTubeライブ、登録URLの簡易表示を目的にしています。
YouTube側に報告する通報機能、コメントやライブチャットの詳細メニューなど、一部のYouTube機能は本アプリ内では利用できない場合があります。
これらの操作が必要な場合は、現在URLをコピーして通常のブラウザで開いてください。

基本操作

- ホーム: ホームボタン、または Ctrl + H で設定済みのホームURLへ移動します。
- 戻る: 戻るボタン、または Alt + ← で前に表示していたページへ戻ります。
- 進む: 進むボタン、または Alt + → で次のページへ進みます。
- 再読み込み: 再読み込みボタン、または Ctrl + R で現在のページを読み込み直します。
- 常に最前面: メインウィンドウを常に最前面に切り替えます。
- フルスクリーン: Alt + Enter で切り替え、Esc で解除します。

アドレスバー

URLを入力して Enter、または 移動 ボタンを押すと、そのページをLiteTube Dock内に表示します。
http:// または https:// がない場合は、https:// を自動で補います。
YouTube内で動画やライブへ移動した場合も、現在表示しているページのURLをアドレスバーへ反映します。
表示メニューから、アドレスバーとナビゲーションボタンの表示 / 非表示を個別に切り替えられます。

外部遷移確認

誤クリック防止として、YouTube以外のページへ移動しようとした場合に確認を表示します。
通常のページ移動だけでなく、新しいウィンドウで開こうとするリンクにも確認を表示します。
確認メッセージは「動画ページ以外へ移動しようとしています。遷移してよろしいですか？」です。
基本設定の 動画ページ以外への遷移を確認する でON/OFFを変更できます。既定値はONです。
確認OFF時でも、新しいウィンドウで開こうとするリンクは、可能な範囲で同じLiteTube Dock内に表示します。
アドレスバー、ホーム、再読み込み、お気に入りボタンなど、ユーザーが明示的に操作した移動は確認なしで実行します。
この機能は広告ブロックではありません。
LiteTube Dock には、YouTube広告を自動でキャンセル、非表示、削除、スキップする機能はありません。

お気に入りボタン

最大10件のお気に入りURLを登録できます。
ボタンを押すと、登録済みURLへ移動します。
設定画面では、表示名、URL、色、アイコン、有効 / 無効を変更できます。
お気に入りごとに、スタート位置、自動再生、ミュート、ループを設定できます。
スタート位置は HH:mm:ss 形式、または 13000 のような数字のみで入力できます。
数字のみの場合は右詰めの時・分・秒として扱い、01:30:00 のように整形します。
空欄は 00:00:00 として扱います。時は24時間を超えても指定できます。
お気に入りを開いた後、動画本編の再生可能範囲を確認してから指定位置へ移動します。
通常動画で動画の長さ以上、ライブ配信で未来位置やDVR範囲外を指定した場合はエラーになります。
YouTube以外のサイトでは、標準的な video / audio 要素で範囲を取得できる場合だけ利用できます。
サイト仕様により開始位置、自動再生、ミュート、ループが利用できない場合があります。
設定画面のお気に入りボタン設定では、各スロットの 削除 ボタンで対象スロットだけを初期値へ戻せます。
削除は番号を詰めず、表示名、URL、有効、色、アイコン、再生設定を既定値へ戻すスロット初期化です。
保存するまでは data/bookmarks.json へ反映されません。キャンセルすると削除前の内容に戻ります。

右クリック登録

お気に入りボタンを右クリックすると、現在再生中のムービーを登録 を使えます。
現在表示中のYouTubeページURLを、そのお気に入り枠へ登録します。
表示名はページタイトルの先頭20文字を仮登録します。
既存登録がある場合は、上書き確認が表示されます。
背景色、文字色、アイコン設定は維持されます。

自動再生

自動再生を使うには、設定画面の「自動再生」をONにして保存し、アプリを再起動してください。

自動再生ONの場合、LiteTube Dockはページの自動再生を試みます。
ただし、YouTube側の仕様により、必ず自動再生されるとは限りません。

お気に入りボタンから動画URLへ移動した場合も、自動再生設定が有効であれば再生開始を試みます。

LiteTube Dock は、YouTubeページ内のボタンを自動で押したり、ページ内容を書き換えたりする操作は行いません。

ループ再生

通常のYouTubeページでループ再生したい場合は、YouTube標準のループ機能を使用してください。
お気に入りのプレイヤーモードでは、動画IDを取得できる場合に loop=1 と playlist=動画ID を付けてループを試みます。

お気に入り設定のインポート / エクスポート

ファイルメニューから、お気に入り設定をファイルとしてインポート / エクスポートできます。
既定の保存先は settings フォルダです。
インポート時は現在のお気に入り設定を上書きし、事前にバックアップを作成します。
ログイン状態、Google ID、パスワード、認証トークンはエクスポート対象ではありません。

多重起動時のお気に入り同期

LiteTube Dock は複数起動できます。
別のLiteTube Dockでお気に入り設定が保存、削除、インポートにより更新された場合、他の起動中画面のお気に入りボタン表示も自動で読み込み直します。
この読み込み直しで現在表示中のページは移動しません。
同期対象はお気に入り設定のみです。
基本設定、ウィンドウ位置、ウィンドウサイズ、現在URL、ログイン状態は同期しません。
設定画面を開いて編集中に外部変更を検知した場合は、再読み込み確認を表示します。
いいえ を選ぶと編集中内容を維持しますが、そのまま保存すると外部変更を上書きする可能性があります。
複数のLiteTube Dockで同時に保存した場合は、最後に保存した内容が優先される可能性があります。

フルスクリーン

Alt + Enter でフルスクリーンを切り替えます。
Esc でフルスクリーンを解除します。
フルスクリーン中は、メニュー、アドレスバー、お気に入りボタン、ステータスバーが非表示になります。
解除後は、アドレスバーなどの表示状態を設定状態へ戻します。

YouTubeログイン・ログアウト

LiteTube Dock は、YouTube / Googleログイン機能を独自実装しません。
ログインはYouTubeの画面上でユーザー自身が行ってください。
ログアウトもYouTube画面上からユーザー自身が行ってください。
Google ID、パスワード、認証トークンは保存しません。
ログイン状態は、アプリ内ブラウザの標準機能に任せます。

ログイン状態のリセット

ログイン状態を完全にリセットしたい場合は、アプリ終了後に以下を削除してください。

data/webview2-user-data

次回起動時に、ログイン状態などを保存するフォルダは自動作成されます。

ウィンドウサイズ

表示メニューまたは設定画面からサイズプリセットを選べます。
横長プリセットと縦長プリセットがあります。
YouTubeショート向けに縦長サイズを選べます。
設定画面の 現在のウィンドウサイズを取得 ボタンで現在サイズを取得できます。
ウィンドウ位置・サイズを初期値に戻す ボタンで既定値へ戻せます。

外部URL制御

通常利用では意識する必要のない内部連携機能として、--ipc-enabled 指定時だけPID別のNamed Pipeを開きます。
Pipe名は LiteTubeDock_{PID} です。
対応コマンドは ping、navigate、get-status です。
診断ログは logs/litetubedock_yyyyMMdd.log に出力します。
get-status ではIPC有効状態、Pipe開始状態、Pipe名、アプリバージョン、最終IPCエラーなどを返します。
navigate は http:// または https:// のURLだけを受け付け、指定URLへ一時的に移動します。
通常起動、--player-mode のみ、--url 指定のみではNamed Pipe待受を開始しません。
Named Pipe経由のURL指定では、LastUrl、お気に入り設定、bookmarks.json は更新しません。
